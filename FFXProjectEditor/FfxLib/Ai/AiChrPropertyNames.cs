    // Friendly names for battle-actor (chr) PROPERTY field ids — the field operand of readChrProperty (0x700F),
    // writeChrProperty (0x7018), getStatField (0x70AA) AND setStatField (0x70AB). All FOUR share the same field
    // space ("btlActorProperty" index in FFXDataParser ScriptFuncLib), so this one table names buff (#6 🛡) AND
    // stat (#6 📊) actions. Replaces the bare "campo 0xNN" / "stat 0xNN".
    //
    // Names are cross-referenced from the public FFX ATEL RE (Karifean/FFXDataParser ScriptConstants.
    // putBattleActorProperty) — same provenance as the codec's func-name table. When the parser has a friendly
    // English name it is used; otherwise the game's own internal symbol (e.g. "stat_round") is used — both are
    // honest and far better than a hex id. Fields 0/2 are HP/maxHP: native
    // 7B2E31 -> 79ADE0 -> actor+5D0 and 7B2E53 -> 79AE00 -> actor+594.
    // Cases 119/11B are predicates (below-half/full HP), not numeric HP getters.
    // Confirmed against PE SHA-256 78ce3439...db5ced, 2026-09-20; see
    // docs/reverse/FFX_ATEL_GAPS_SEYMOUR_ANIMA_2026-09-20.md. Recipe/target
    // writer migration is separate from these labels; existing gates remain.
    //
    // ── WRITE SIDE (0x7018 = writeChrProperty, confirmed via IDA) ──
    // The write dispatcher (FFX_Btl_ATEL_DispatchOpcode @ 0x7B4B80) has a 346-case switch that MIRRORS
    // the read side but WRITES to actor struct offsets. Key write cases (IDA-verified):
    //   case  0 → [esi+5D0h] = WriteCurrentHp     case  2 → [esi+594h] = WriteMaxHp
    //   case  1 → [esi+5D4h] = WriteCurrentMp     case  3 → [esi+598h] = WriteMaxMp
    //   cases 4-7 → [esi+606h] XOR+mask = ToggleStatusBit (bit0=death/damage, bit1-3=other)
    //   case  9 → [esi+5A8h] = WriteSTR (recalculates max stat via ComputeActorMaxStat!)
    //   cases 10-16 → WriteDEF/MAG/MDEF/AGI/LUCK/EVA/ACC
    //   case 21 → [esi+0DC8h] = WriteActorTurnState
    //   case 26 → [esi+505h] = WriteIsFlying
    //   case 31 → [esi+504h] &7 = WriteOverdriveSkillByte (low 3 bits)
    //   cases 32-36 → [esi+5B8h] = statusWord5B8 bitfield
    //   cases 37-44 → [esi+606h] = statusWord606 bitfield
    //   case 45 → [esi+608h] = WriteOverdriveThreshold
    //   cases 48-57 → [esi+60Bh..0x614h] = status durations (Shell/Protect/Reflect/NulTide/NulBlaze/
    //                  NulShock/NulFrost/Regen/Haste/Slow) — CONFIRMS 0x613=Haste, 0x614=Slow
    //   case 55 (Regen) → side-effect: clears [esi+6D2h] (Poison/Regen counter reset)
    //   cases 58-69 → [esi+6BCh] = statusWord6BC bitfield
    //   cases 70-71 → [esi+6BCh] toggle bits 11-12; case 74 → bit 13
    //   case 76 → [esi+6BEh] OR bit 15; cases 77-78 → [esi+6C0h] toggle bits 0-1
    //   case 79 → [esi+3F5h]+[esi+3F6h] = WriteDeathAnimation (2 bytes!)
    //   case 82 → [esi+0DD9h] = WriteTargetable; case 84 → ResetActorState (no offset, calls function)
    //   case 87 → [esi+0E2Ch] = WriteChrHandle + SetParentResourceSlot
    //   case 95 → [esi+508h] = WriteActionLocked; case 97 → [esi+50Eh]+clear[esi+50Fh]
    //   cases 98-109 → [esi+5DAh..5DCh] = status flags bitfields
    //   cases 110-117 → [esi+5DCh..5DDh] = status flags continued
    //   case 127 → SetActorOpacityState (function call, no offset)
    //   cases 129-132, 138-141 → write to dereferenced model data pointers (not actor struct directly)
    //   case 142 → [esi+0DD2h] = WriteMustBeKilledForBattleEnd (confirms read side)
    //   cases 143-149 → [esi+616h] toggle bits 0-6 = statusWord616
    //   cases 150-157 → [esi+616h] toggle bits 7-14; case 151 = Reflect (side-effect: HandleReflectOrDamage)
    //   case 158 → [esi+4ACh] = WriteDword4AC; cases 159-160 → [esi+5C8h..5C9h]
    //   case 166 → [esi+0D34h] = WriteLastDamageTakenHP (confirms read side field 0xA6)
    //   case 173 → [esi+0DCDh] = WriteLastAttacker (confirms target sentinel 0xFFEF)
    //   case 174 → ResetActorStateWithParam (function call, no offset)
    //   cases 176-199 → [esi+642h..659h] = 24 consecutive bytes (equipment/ability slots)
    //   cases 200-214 → [esi+65Ah] toggle bits 0-14 = statusWord65A
    //   case 216 → SetVisibility; case 218 → [esi+4B0h] = WriteWord4B0 (HP ratio?)
    //   case 219 → [esi+4B2h] = WriteWord4B2 (MP ratio?)
    //   case 237 → SetEffectState; case 240 → [esi+5B8h] toggle bit 8
    //   case 241 → SetVisibilityPriority; case 242 → [esi+5D0h]=0 = KILL ACTOR (death!)
    //   case 251 → SetActionFlagActive
    //   DEFAULT: after each write, calls BuildActorStatusEffectDescriptorRows + PropagateActorStatusEffects
    //            if death (var_18==2), triggers DeathHandler_CallsOverdriveKillEvent
    //   case 261 → [esi+4E8h] = WriteScaleFloat + sets [esi+44Dh]=1
    //   case 270-272 → SetScaleFrom3A8 / SetSpeedScale / SetSizeScale (function calls)
    //   case 273 → AccumulateGlobalCounter; case 276 → [esi+6DFh] = WriteTurnsTaken (confirms 0x0114)
    //   case 279 → [esi+6E1h] clamp 0-100; case 280 → [esi+5BCh] clamp 0-255 using [esi+5BDh] as max
    //   cases 292-293 → [esi+4ACh] AND NOT / OR = clear/set bitfield bits
    //   cases 302-309 → [esi+5B0h..5B7h] = 8 consecutive stat bytes (sets var_10=1 = "stat modified" flag)
    //   cases 314-329 → 16 fields on dereferenced model data pointer (offsets 0x00-0x23)
    //   case 330 → [esi+3F9h] = WriteHasActiveAction; case 334 → [esi+3Bh] = SetDeathFlag
    //   case 333 → AssignPartySlot (function call)
    //   COMPLETE: all 346 write cases mapped. Struct = 3984 bytes (0xF90). ~60% coverage.
    // NulHoly/NulDark do NOT exist in the binary — cut features.
