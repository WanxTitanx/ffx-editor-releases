    // Stack-effect model for the ATEL VM — powers the AI Assembler's stack-balance checker ("Mini-corretora",
    // Level 1). Two proven tables:
    //   • NetNonCall(opcode) — the net stack change of every non-call opcode (push count − pop count), derived
    //     from FFXDataParser ScriptConstants.OPCODE_STACKPOPS + the push semantics of each opcode family.
    //   • CallArgCount(funcId) — how many args a native CALL/CALLPOPA pops, = the function's input count in
    //     FFXDataParser ScriptFuncLib (regular funcs: number of params; accessors: subject?+index+value?). 269
    //     functions. A CALL (0xB5) nets +1 − args (pushes the return); a CALLPOPA (0xD8) nets −args (void).
    // Cross-referenced from the public FFX ATEL RE (Karifean/FFXDataParser) — same provenance as the name tables.
    // Dependency-free. Null returns mean "unknown" so the checker can stay HONEST (it stops asserting past an
    // unknown-arity call instead of guessing).
    public static class AiStackModel
    {
        /// <summary>Net stack change of a NON-call opcode (push − pop), or null if the opcode is not modelled
        /// (CALL/CALLPOPA are handled via CallArgCount; truly-unknown opcodes return null).</summary>
        public static int? NetNonCall(byte opcode) => opcode switch
        {
            0x00 => 0,                 // NOP
            // binary operators (pop 2, push 1) — comparison / logic / arithmetic / shift
            0x01 or 0x02 or 0x03 or 0x04 or 0x05 or 0x06 or 0x07 or 0x08 or 0x09
                or 0x0A or 0x0B or 0x0C or 0x0D or 0x0E or 0x0F or 0x12 or 0x13 or 0x14 or 0x15 or 0x16 or 0x17 or 0x18 => -1,
            0x19 => 0,                 // NOT (unary: pop 1, push 1)
            0x29 => 1,                 // PUSHY / GET_CASE
            0x2A => -1,                // POPX / SET_TEST
            0x2B => 1,                 // REPUSH / COPY (duplicate top)
            0x2C => -1,                // POPY / SET_CASE
            0x3C => 0,                 // RET / END
            0x59 or 0x5A or 0x5B or 0x5C or 0x5D or 0x5E or 0x60 => -1,   // POPI/F (store temp reg)
            0x67 or 0x68 or 0x69 or 0x6A or 0x6B or 0x6C or 0x6E => 1,    // PUSHI/F (load temp reg)
            0x9F => 1,                 // PUSHV / GET_DATUM (load var)
            0xA0 => -1,                // POPV / SET_DATUM (store var)
            0xA2 => 0,                 // PUSHAR (pop index, push element)
            0xA3 => -2,                // POPAR (pop index + value)
            0xAD or 0xAE or 0xAF => 1, // PUSHI / PUSHII / PUSHF (push constant)
            0xB0 => 0,                 // JMP
            0xD6 or 0xD7 => -1,        // POPXCJMP / POPXNCJMP (pop the condition)
            _ => null,                 // 0xB5 CALL / 0xD8 CALLPOPA handled by the caller; anything else = unknown
        };

        /// <summary>How many args a native call (CALL/CALLPOPA) pops for this func-id, or null when the function
        /// isn't in the RE table (the checker then stops asserting past it).</summary>
        public static int? CallArgCount(ushort funcId) => _argCount.TryGetValue(funcId, out int n) ? n : (int?)null;

public static string? CallDisplayName(ushort funcId) => AiCallNameCatalog.DisplayName(funcId);

